def get_time_of_day(hour: int = None) -> str:
    """根据小时返回时间段名称"""
    if hour is None:
        hour = datetime.now().hour
    if 0 <= hour < 5:
        return "深夜"
    elif 5 <= hour < 7:
        return "凌晨"
    elif 7 <= hour < 9:
        return "清晨"
    elif 9 <= hour < 12:
        return "上午"
    elif 12 <= hour < 14:
        return "中午"
    elif 14 <= hour < 17:
        return "下午"
    elif 17 <= hour < 19:
        return "傍晚"
    elif 19 <= hour < 23:
        return "夜晚"
    else:
        return "深夜"
