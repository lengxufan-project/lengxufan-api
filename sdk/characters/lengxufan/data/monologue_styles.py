def get_monologue_template(emotion_level: float) -> str:
    """根据情绪值返回对应的独白风格名称"""
    if emotion_level < 30:
        return "低落"
    elif emotion_level < 50:
        return "平静"
    elif emotion_level < 70:
        return "稍好"
    else:
        return "高涨"
